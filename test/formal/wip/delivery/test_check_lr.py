def main():
    bad = 0
    for what, sent, recv, echo, scene, must_fail, *isupport in CASES:
        fails = run(sent, recv, echo, scene, *isupport)
        ok = bool(fails) == must_fail
        bad += not ok
        print(f"{'ok  ' if ok else 'BAD '} {what}: {fails or 'holds'}")
    return 1 if bad else 0


