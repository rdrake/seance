#!/bin/sh
# Writes the configs (run TLC on MC.tla). Usage: sh mkcfg.sh
# cfg NAME "overrides" "INVARIANTS" "PROPERTIES"
cfg() {
  name=$1; over=$2; inv=$3; props=$4
  {
    echo "\\* generated by mkcfg.sh"
    echo "SPECIFICATION Spec"
    echo "CONSTANTS"
    # defaults, overridden by $over (KEY=VALUE pairs separated by ;)
    for kv in 'Chans={"a","b","c"}' 'RestoredSeq=<-SeqAB' 'Nested={"b"}' \
              'Active="a"' 'Alias=TRUE' 'Cursor=TRUE' 'Quiet=3' 'InitialWait=8' \
              'Cap=32' 'MaxGap=2' 'StallOK=FALSE' 'Endless=FALSE' 'Rule="pr282"' \
              'CloseActivity=TRUE' 'HasCap=TRUE'; do
      k=${kv%%=*}
      v=$(printf '%s\n' "$over" | tr ';' '\n' | sed -n "s/^ *$k=//p" | tail -1)
      [ -n "$v" ] || v=${kv#*=}
      case $v in '<-'*) echo "  $k $v";; *) echo "  $k = $v";; esac
    done
    echo "INVARIANTS"
    echo "  $inv"
    [ -n "$props" ] && { echo "PROPERTIES"; echo "  $props"; }
    echo "CHECK_DEADLOCK TRUE"
  } > "$name.cfg"
}
